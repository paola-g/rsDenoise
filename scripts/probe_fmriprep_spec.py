"""Detect fmriprep output-spec drift and report it as JSON.

Used by the release-watch workflow.  With ``--source-dir`` it can run entirely
offline against a checked-out fmriprep tree (useful for tests).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "rsdenoise" / "fmriprep_spec.json"

PYPI_URL = "https://pypi.org/pypi/fmriprep/json"
RAW = "https://raw.githubusercontent.com/nipreps/fmriprep/{tag}/{path}"

SOURCE_FILES = {
    "confounds_workflow": "fmriprep/workflows/bold/confounds.py",
    "confounds_interface": "fmriprep/interfaces/confounds.py",
    "bold_base": "fmriprep/workflows/bold/base.py",
}

PREFIX_RE = re.compile(r"header_prefix\s*=\s*['\"]([^'\"]+)['\"]")
# fMRIPrep also builds names with f-strings, e.g. f'a_comp_cor_{i:02d}'.
LITERAL_RE = re.compile(r"(?:f)?['\"]([a-z][a-z0-9_]*)")
PREFIX_KEYWORDS = ("comp_cor", "outlier", "cosine", "aroma")
# Match a keyword only as a whole underscore-delimited token, so unrelated
# literals such as 'outliers' don't look like new confound prefixes.
PREFIX_KEYWORD_RE = re.compile(
    r"(?:^|_)(?:{0})(?:_|$)".format("|".join(map(re.escape, PREFIX_KEYWORDS))))
SUFFIX_RE = re.compile(r"suffix\s*=\s*['\"](timeseries|regressors)['\"]")


def _fetch(url: str, timeout: int = 30) -> str:
    with urllib.request.urlopen(url, timeout=timeout) as response:
        return response.read().decode("utf-8")


def stable_version() -> str:
    return json.loads(_fetch(PYPI_URL))["info"]["version"]


def source_files(version: str, source_dir: Path | None) -> dict[str, str]:
    if source_dir is not None:
        return {name: (source_dir / path).read_text(encoding="utf-8")
                for name, path in SOURCE_FILES.items()}
    return {name: _fetch(RAW.format(tag=version, path=path))
            for name, path in SOURCE_FILES.items()}


def extract_prefixes(sources: dict[str, str]) -> list[str]:
    found: set[str] = set()
    for name in ("confounds_workflow", "confounds_interface"):
        text = sources.get(name, "")
        found.update(PREFIX_RE.findall(text))
        for token in LITERAL_RE.findall(text):
            if PREFIX_KEYWORD_RE.search(token):
                found.add(token)
    return sorted(found)


def extract_confounds_suffix(sources: dict[str, str]) -> str | None:
    matches = SUFFIX_RE.findall(sources.get("bold_base", ""))
    return matches[0] if matches else None


def compare(spec: dict, version: str, sources: dict[str, str]) -> dict:
    expectations = spec["confounds"]
    prefixes = extract_prefixes(sources)
    known = set(expectations["component_prefixes"]) | set(
        expectations.get("removed_prefixes", []))
    suffix = extract_confounds_suffix(sources)
    patterns = spec["file_patterns"]["confounds"]
    expected_suffix = "timeseries" if any(
        "confounds_timeseries" in p for p in patterns) else "regressors"

    new_prefixes = [p for p in prefixes if p not in known]
    missing_prefixes = [
        p for p in expectations["component_prefixes"]
        if not any(p.startswith(found) or found.startswith(p) for found in prefixes)
    ]
    drift = {
        "new_version": version,
        "recorded_version": spec["fmriprep"]["stable_version"],
        "new_prefixes": new_prefixes,
        "missing_prefixes": missing_prefixes,
        "confounds_suffix": suffix,
        "expected_confounds_suffix": expected_suffix,
    }
    drift["version_changed"] = version != drift["recorded_version"]
    drift["columns_changed"] = bool(new_prefixes)
    # Missing prefixes are informational: some are generated by pinned
    # dependencies (niworkflows/nipype) rather than by fmriprep source, so
    # failing to detect them must not open a PR on every scheduled run.
    drift["columns_missing"] = bool(missing_prefixes)
    drift["filename_changed"] = suffix is not None and suffix != expected_suffix
    drift["requires_changes"] = (
        drift["version_changed"] or drift["columns_changed"]
        or drift["filename_changed"]
    )
    return drift


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path,
                        help="local fmriprep checkout (offline mode)")
    parser.add_argument("--version", help="override the detected version")
    parser.add_argument("--report", type=Path,
                        help="write the JSON report to this file")
    args = parser.parse_args()

    spec = json.loads(SPEC_PATH.read_text(encoding="utf-8"))
    version = args.version or ("0.0.0" if args.source_dir else stable_version())
    sources = source_files(version, args.source_dir)
    drift = compare(spec, version, sources)

    report = json.dumps(drift, indent=2, sort_keys=True)
    print(report)
    if args.report:
        args.report.write_text(report + "\n", encoding="utf-8")
    return 2 if drift["requires_changes"] else 0


if __name__ == "__main__":
    sys.exit(main())
