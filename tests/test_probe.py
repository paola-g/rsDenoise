import json
from pathlib import Path

from scripts.probe_fmriprep_spec import (
    compare,
    extract_confounds_suffix,
    extract_prefixes,
)

SPEC = json.loads(
    (Path(__file__).parents[1] / "rsdenoise" / "fmriprep_spec.json").read_text(
        encoding="utf-8")
)


def _sources(prefixes, suffix="timeseries"):
    lines = "\n".join(f"x = foo(header_prefix='{p}')" for p in prefixes)
    return {
        "confounds_workflow": lines,
        "confounds_interface": lines,
        "bold_base": f"boldwf = Workflow(suffix='{suffix}')",
    }


def test_extractors():
    sources = _sources(["a_comp_cor_", "cosine"])
    assert extract_prefixes(sources) == ["a_comp_cor_", "cosine"]
    assert extract_confounds_suffix(sources) == "timeseries"


def test_no_drift_for_known_spec():
    prefixes = (SPEC["confounds"]["component_prefixes"]
                + SPEC["confounds"]["removed_prefixes"])
    drift = compare(SPEC, "25.2.7", _sources(prefixes))
    assert drift["version_changed"] is False
    assert drift["requires_changes"] is False


def test_missing_prefixes_alone_do_not_trigger_a_pr():
    # Some prefixes are generated by pinned dependencies, so absence from
    # fmriprep source is expected and must not cause weekly noise.
    drift = compare(SPEC, SPEC["fmriprep"]["stable_version"], _sources([]))
    assert drift["columns_missing"] is True
    assert drift["columns_changed"] is False
    assert drift["requires_changes"] is False


def test_drift_detected_for_new_column_and_filename():
    prefixes = (SPEC["confounds"]["component_prefixes"]
                + SPEC["confounds"]["removed_prefixes"]
                + ["new_fancy_comp_"])
    drift = compare(SPEC, "26.0.0", _sources(prefixes, suffix="regressors"))
    assert drift["version_changed"] is True
    assert "new_fancy_comp_" in drift["new_prefixes"]
    assert drift["filename_changed"] is True
    assert drift["requires_changes"] is True


def test_keyword_only_counts_as_a_whole_token():
    # Unrelated literals that merely contain a keyword substring must not be
    # reported as new confound prefixes (which would open a spurious PR).
    sources = {
        "confounds_workflow": "\n".join([
            "a = 'outliers'",            # contains 'outlier'
            "b = 'n_aromatic'",          # contains 'aroma'
            "c = f'motion_outlier{i:02d}'",
        ]),
        "confounds_interface": "",
        "bold_base": "boldwf = Workflow(suffix='timeseries')",
    }
    found = extract_prefixes(sources)
    assert "outliers" not in found
    assert "n_aromatic" not in found
    assert "motion_outlier" in found
